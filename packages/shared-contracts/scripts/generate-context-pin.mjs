#!/usr/bin/env node
// node scripts/generate-context-pin.mjs
//
// Writes packages/shared-contracts/src/generated/context-pin.ts, which git
// ignores, from the root agent-context.pin.json on every build, so Workers
// never read the filesystem for the Context Pin:
//
//   CONTEXT_PIN  the pinned Zero-State-LLC/agent-context commit, when it was
//                pinned, and the sha256 of each file Homer consumes
//
// Changing the pin is a reviewed pull request; this script only copies it.
import { mkdirSync, readFileSync, realpathSync, renameSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { repositoryRoot } from "../../../scripts/check-versions.mjs";

export const CONTEXT_PIN_PATH = "packages/shared-contracts/src/generated/context-pin.ts";
export const PIN_FILE = "agent-context.pin.json";

const COMMIT = /^[0-9a-f]{40}$/;
const PINNED_AT = /^\d{4}-\d{2}-\d{2}$/;
const SHA256 = /^[0-9a-f]{64}$/;

/** The pinned repository, commit, date and file hashes, or throws. */
export function readContextPin(rootDir) {
  const value = JSON.parse(readFileSync(join(rootDir, PIN_FILE), "utf8"));
  if (value === null || typeof value !== "object" || Array.isArray(value)) {
    throw new Error(`${PIN_FILE} must be a JSON object`);
  }
  const { repository, commit, pinnedAt, files } = value;
  if (typeof repository !== "string" || repository.length === 0) {
    throw new Error(`${PIN_FILE}: repository must be a non-empty string`);
  }
  if (typeof commit !== "string" || !COMMIT.test(commit)) {
    throw new Error(`${PIN_FILE}: commit must be a 40-character lowercase hex sha`);
  }
  if (typeof pinnedAt !== "string" || !PINNED_AT.test(pinnedAt)) {
    throw new Error(`${PIN_FILE}: pinnedAt must be YYYY-MM-DD`);
  }
  if (files === null || typeof files !== "object" || Array.isArray(files)) {
    throw new Error(`${PIN_FILE}: files must map each consumed path to its sha256`);
  }
  for (const [path, hash] of Object.entries(files)) {
    if (typeof hash !== "string" || !SHA256.test(hash)) {
      throw new Error(`${PIN_FILE}: ${path} must be a 64-character lowercase hex sha256`);
    }
  }
  return { repository, commit, pinnedAt, files };
}

export function render({ repository, commit, pinnedAt, files }) {
  const entries = Object.entries(files).map(
    ([path, hash]) => `  ${JSON.stringify(path)}: ${JSON.stringify(hash)},`,
  );
  return [
    "// Generated by scripts/generate-context-pin.mjs on every build.",
    "// Git ignores this file; do not edit it.",
    'import type { ContextPinSnapshot } from "../types.js";',
    "",
    "const FILES: Readonly<Record<string, string>> = {",
    ...entries,
    "};",
    "",
    "export const CONTEXT_PIN: ContextPinSnapshot = Object.freeze({",
    `  repository: ${JSON.stringify(repository)},`,
    `  commit: ${JSON.stringify(commit)},`,
    `  pinnedAt: ${JSON.stringify(pinnedAt)},`,
    "  files: FILES,",
    "});",
    "",
  ].join("\n");
}

/** Writes the file when its content changes, and returns the pin. */
export function writeContextPin(rootDir) {
  const pin = readContextPin(rootDir);
  const target = join(rootDir, CONTEXT_PIN_PATH);
  const text = render(pin);
  let old;
  try {
    old = readFileSync(target, "utf8");
  } catch {
    old = undefined;
  }
  if (old !== text) {
    mkdirSync(dirname(target), { recursive: true });
    const temporary = `${target}.${process.pid}.tmp`;
    writeFileSync(temporary, text);
    renameSync(temporary, target);
  }
  return pin;
}

function isMain() {
  if (!process.argv[1]) return false;
  try {
    return realpathSync(process.argv[1]) === realpathSync(fileURLToPath(import.meta.url));
  } catch {
    return false;
  }
}

if (isMain()) {
  try {
    const pin = writeContextPin(repositoryRoot());
    console.log(`Context Pin ${pin.repository}@${pin.commit.slice(0, 7)}`);
  } catch (error) {
    console.error(`generate-context-pin: ${error.message}`);
    process.exit(1);
  }
}
