// Tests for the Build Version (versioning spec, "The build version"):
// scripts/build-info.mjs and what the build left in @zs-home/shared-contracts.
// `npm run build` runs these after building, as it runs every *runtime.test.mjs.
import { test } from "node:test";
import assert from "node:assert/strict";
import { execFileSync } from "node:child_process";
import { mkdtempSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join } from "node:path";
import { BUILD_INFO_PATH, buildInfo, readGit, render, writeBuildInfo } from "./build-info.mjs";
import { repositoryRoot } from "./check-versions.mjs";

const repo = repositoryRoot();
const SHA = "a1b2c3d4e5f60718293a4b5c6d7e8f9012345678";

function temporary(t) {
  const dir = mkdtempSync(join(tmpdir(), "homer-build-info-"));
  t.after(() => rmSync(dir, { recursive: true, force: true }));
  return dir;
}

// A stand-in for git that answers for `root`.
function fakeGit(root, { head = SHA, status = "", top = root } = {}) {
  return (_cwd, args) => {
    if (args[0] === "rev-parse" && args[1] === "--show-toplevel") return `${top}\n`;
    if (args[0] === "rev-parse") return `${head}\n`;
    if (args[0] === "status") return status;
    throw new Error(`unexpected git ${args.join(" ")}`);
  };
}

function workspace(t, version = "0.1.0") {
  const dir = temporary(t);
  writeFileSync(join(dir, "package.json"), JSON.stringify({ name: "homer", version }) + "\n");
  return dir;
}

test("a clean checkout builds X.Y.Z+<7 characters of the commit>", (t) => {
  const dir = workspace(t);
  assert.deepEqual(buildInfo(dir, fakeGit(dir)), {
    productVersion: "0.1.0",
    commit: "a1b2c3d",
    buildVersion: "0.1.0+a1b2c3d",
  });
});

test("a changed or untracked file marks the build .dirty", (t) => {
  const dir = workspace(t);
  for (const status of [" M package.json\n", "?? new-file.ts\n", "D  gone.ts\n"]) {
    assert.equal(buildInfo(dir, fakeGit(dir, { status })).buildVersion, "0.1.0+a1b2c3d.dirty");
  }
});

test("without git, a repository or a commit, the commit is unknown", (t) => {
  const dir = workspace(t);
  const failing = () => {
    throw new Error("spawn git ENOENT");
  };
  const elsewhere = temporary(t);
  for (const git of [
    failing,
    fakeGit(dir, { head: "not-a-sha" }),
    fakeGit(dir, { top: elsewhere }), // a folder inside some other repository
  ]) {
    assert.deepEqual(readGit(dir, git), { commit: "unknown", dirty: false });
    assert.equal(buildInfo(dir, git).buildVersion, "0.1.0+unknown");
  }
});

test("a release candidate keeps its prerelease before the build metadata", (t) => {
  const dir = workspace(t, "0.1.0-rc.1");
  assert.equal(buildInfo(dir, fakeGit(dir)).buildVersion, "0.1.0-rc.1+a1b2c3d");
});

test("a root version that is not a product version stops the build", (t) => {
  for (const version of [null, "banana", "0.1.0+meta"]) {
    const dir = workspace(t, version);
    assert.throws(() => buildInfo(dir, fakeGit(dir)), /not a product version/);
  }
});

test("the generated module exports exactly the three values", () => {
  const text = render({
    productVersion: "0.1.0",
    commit: "a1b2c3d",
    buildVersion: "0.1.0+a1b2c3d",
  });
  assert.match(text, /^\/\/ Generated by scripts\/build-info\.mjs/);
  assert.deepEqual(
    [...text.matchAll(/^export const (\w+) = (".*");$/gm)].map((m) => [m[1], JSON.parse(m[2])]),
    [
      ["PRODUCT_VERSION", "0.1.0"],
      ["BUILD_COMMIT", "a1b2c3d"],
      ["BUILD_VERSION", "0.1.0+a1b2c3d"],
    ],
  );
});

test("writing twice leaves the file untouched when nothing changed", (t) => {
  const dir = workspace(t);
  writeBuildInfo(dir, fakeGit(dir));
  const first = readFileSync(join(dir, BUILD_INFO_PATH), "utf8");
  writeBuildInfo(dir, fakeGit(dir));
  assert.equal(readFileSync(join(dir, BUILD_INFO_PATH), "utf8"), first);
  writeBuildInfo(dir, fakeGit(dir, { status: " M x\n" }));
  assert.match(readFileSync(join(dir, BUILD_INFO_PATH), "utf8"), /0\.1\.0\+a1b2c3d\.dirty/);
});

test("real git: clean, changed, untracked, ignored, and no repository", (t) => {
  try {
    execFileSync("git", ["--version"], { stdio: "ignore" });
  } catch {
    t.skip("git is not installed");
    return;
  }
  const dir = workspace(t);
  const git = (...args) =>
    execFileSync(
      "git",
      ["-c", "user.name=Homer test", "-c", "user.email=test@example.invalid", ...args],
      { cwd: dir, encoding: "utf8", stdio: ["ignore", "pipe", "ignore"] },
    );
  assert.equal(buildInfo(dir).buildVersion, "0.1.0+unknown", "a folder that is not a repository");
  git("init", "-q");
  assert.equal(buildInfo(dir).buildVersion, "0.1.0+unknown", "a repository with no commit");
  writeFileSync(join(dir, ".gitignore"), "ignored.txt\n");
  git("add", "-A");
  git("commit", "-q", "--no-gpg-sign", "-m", "fixture");
  const head = git("rev-parse", "HEAD").trim().slice(0, 7);
  assert.equal(buildInfo(dir).buildVersion, `0.1.0+${head}`);
  writeFileSync(join(dir, "ignored.txt"), "x");
  assert.equal(buildInfo(dir).buildVersion, `0.1.0+${head}`, "an ignored file is not a change");
  writeFileSync(join(dir, "untracked.txt"), "x");
  assert.equal(buildInfo(dir).buildVersion, `0.1.0+${head}.dirty`);
  rmSync(join(dir, "untracked.txt"));
  writeFileSync(join(dir, ".gitignore"), "ignored.txt\nmore\n");
  assert.equal(buildInfo(dir).buildVersion, `0.1.0+${head}.dirty`);
});

test("the build wrote this checkout's version into @zs-home/shared-contracts", async () => {
  const built = await import("@zs-home/shared-contracts/workers");
  const node = await import("@zs-home/shared-contracts");
  const expected = buildInfo(repo);
  assert.equal(built.PRODUCT_VERSION, expected.productVersion);
  assert.equal(built.BUILD_COMMIT, expected.commit);
  // Later build steps may touch files, so the dirty mark can differ from now.
  const v = expected.productVersion;
  const allowed =
    expected.commit === "unknown"
      ? [`${v}+unknown`]
      : [`${v}+${expected.commit}`, `${v}+${expected.commit}.dirty`];
  assert.ok(allowed.includes(built.BUILD_VERSION), built.BUILD_VERSION);
  assert.equal(node.BUILD_VERSION, built.BUILD_VERSION);
});

test("git ignores the generated file", (t) => {
  try {
    execFileSync("git", ["check-ignore", "-q", BUILD_INFO_PATH], { cwd: repo, stdio: "ignore" });
  } catch (error) {
    if (readGit(repo).commit === "unknown") {
      t.skip("not a git checkout");
      return;
    }
    throw error;
  }
});
