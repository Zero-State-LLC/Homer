#!/usr/bin/env node
// node scripts/build-info.mjs
//
// Writes packages/shared-contracts/src/generated/build-info.ts, which git
// ignores, on every build (versioning spec, "The build version"):
//
//   PRODUCT_VERSION  the root package.json version, as in 0.1.0
//   BUILD_COMMIT     the first 7 characters of HEAD, or "unknown" without git
//   BUILD_VERSION    0.1.0+a1b2c3d, with ".dirty" when the working tree has
//                    changes, or 0.1.0+unknown without git
//
// Every Collector writes BUILD_VERSION as Provenance's collectorVersion. The
// values come from the checkout being built, never from the environment, so
// a Collector cannot be told its version.
import { execFileSync } from "node:child_process";
import { mkdirSync, readFileSync, realpathSync, renameSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { SEMVER, repositoryRoot } from "./check-versions.mjs";

export const BUILD_INFO_PATH = "packages/shared-contracts/src/generated/build-info.ts";

const UNKNOWN = { commit: "unknown", dirty: false };

/** Runs git in `cwd` and returns its output, or throws. */
function runGit(cwd, args) {
  return execFileSync("git", args, {
    cwd,
    encoding: "utf8",
    stdio: ["ignore", "pipe", "ignore"],
    // Reading status must not take the index lock another git may hold.
    env: { ...process.env, GIT_OPTIONAL_LOCKS: "0" },
  });
}

/**
 * The commit and whether the working tree has changes, including untracked
 * files git does not ignore. Anything git cannot answer for this exact
 * repository root is "unknown": no git, no repository, no commit yet, or a
 * root that is only a folder inside some other repository.
 */
export function readGit(rootDir, git = runGit) {
  try {
    const top = git(rootDir, ["rev-parse", "--show-toplevel"]).trim();
    if (realpathSync(top) !== realpathSync(rootDir)) return UNKNOWN;
    const head = git(rootDir, ["rev-parse", "--verify", "HEAD"]).trim();
    if (!/^(?:[0-9a-f]{40}|[0-9a-f]{64})$/.test(head)) return UNKNOWN;
    const status = git(rootDir, ["status", "--porcelain=v1", "--untracked-files=normal"]);
    return { commit: head.slice(0, 7), dirty: status.trim() !== "" };
  } catch {
    return UNKNOWN;
  }
}

/** The three build values for the checkout at `rootDir`. */
export function buildInfo(rootDir, git = runGit) {
  const productVersion = JSON.parse(readFileSync(join(rootDir, "package.json"), "utf8")).version;
  if (typeof productVersion !== "string" || !SEMVER.test(productVersion)) {
    throw new Error(`package.json: version "${productVersion}" is not a product version`);
  }
  const { commit, dirty } = readGit(rootDir, git);
  const metadata = commit === "unknown" ? "unknown" : dirty ? `${commit}.dirty` : commit;
  return { productVersion, commit, buildVersion: `${productVersion}+${metadata}` };
}

export function render({ productVersion, commit, buildVersion }) {
  return [
    "// Generated by scripts/build-info.mjs on every build.",
    "// Git ignores this file; do not edit it.",
    `export const PRODUCT_VERSION = ${JSON.stringify(productVersion)};`,
    `export const BUILD_COMMIT = ${JSON.stringify(commit)};`,
    `export const BUILD_VERSION = ${JSON.stringify(buildVersion)};`,
    "",
  ].join("\n");
}

/** Writes the file when its content changes, and returns the build values. */
export function writeBuildInfo(rootDir, git = runGit) {
  const info = buildInfo(rootDir, git);
  const target = join(rootDir, BUILD_INFO_PATH);
  const text = render(info);
  let old;
  try {
    old = readFileSync(target, "utf8");
  } catch {
    old = undefined;
  }
  if (old !== text) {
    mkdirSync(dirname(target), { recursive: true });
    const temporary = `${target}.${process.pid}.tmp`;
    writeFileSync(temporary, text);
    renameSync(temporary, target);
  }
  return info;
}

function isMain() {
  if (!process.argv[1]) return false;
  try {
    return realpathSync(process.argv[1]) === realpathSync(fileURLToPath(import.meta.url));
  } catch {
    return false;
  }
}

if (isMain()) {
  try {
    const info = writeBuildInfo(repositoryRoot());
    console.log(`Build Version ${info.buildVersion}`);
  } catch (error) {
    console.error(`build-info: ${error.message}`);
    process.exit(1);
  }
}
